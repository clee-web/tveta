def _current_teacher(db):
    teacher = db.execute(
        "SELECT * FROM teachers WHERE id = ?", (session["teacher_id"],)
    ).fetchone()
    if not teacher:
        session.clear()
        abort(403)
    return teacher


def _teacher_classes(db, teacher_id):
    return db.execute(
        """SELECT c.* FROM classes c
           JOIN teacher_classes tc ON tc.class_id = c.id
           WHERE tc.teacher_id = ?
           ORDER BY c.academic_year DESC, c.name COLLATE NOCASE""",
        (teacher_id,),
    ).fetchall()


def _class_for_teacher(db, teacher_id, class_id):
    cls = db.execute(
        """SELECT c.* FROM classes c
           JOIN teacher_classes tc ON tc.class_id = c.id
           WHERE tc.teacher_id = ? AND c.id = ?""",
        (teacher_id, class_id),
    ).fetchone()
    if not cls:
        abort(403)
    return cls


def _exam_for_teacher(db, teacher_id, exam_id):
    exam = db.execute(
        """SELECT e.* FROM exams e
           JOIN teacher_classes tc ON tc.class_id = e.class_id
           WHERE e.id = ? AND tc.teacher_id = ?""",
        (exam_id, teacher_id),
    ).fetchone()
    if not exam:
        abort(404)
    return exam
