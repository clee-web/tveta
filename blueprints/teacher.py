def _exams_context(db, teacher):
    classes = _teacher_classes(db, teacher["id"])
    class_ids = [c["id"] for c in classes]

    exam_rows = []
    subjects = []
    if class_ids:
        placeholders = ",".join("?" for _ in class_ids)
        exam_rows = db.execute(
            f"""SELECT e.*, c.name AS class_name, s.name AS subject_name,
                  (SELECT COUNT(*) FROM exam_results r WHERE r.exam_id = e.id) AS result_count
                FROM exams e
                JOIN classes c ON c.id = e.class_id
                LEFT JOIN class_subjects s ON s.id = e.subject_id
                WHERE e.class_id IN ({placeholders})
                ORDER BY e.created_at DESC""",
            class_ids,
        ).fetchall()

        subjects = db.execute(
            f"""SELECT * FROM class_subjects
               WHERE class_id IN ({placeholders})
               ORDER BY name COLLATE NOCASE""",
            class_ids,
        ).fetchall()

    subjects_by_class = {}
    for s in subjects:
        subjects_by_class.setdefault(s["class_id"], []).append(s)

    # Each class runs a course, and courses are labelled differently - terms,
    # semesters or the two stages of a short course - so the exam form can only
    # offer the periods this student group actually has.
    ladders = ladders_by_course(db)
    terms_by_class = {c["id"]: ladders.get(c["course"], TERMS) for c in classes}

    return {
        "teacher": teacher,
        "classes": classes,
        "exams": exam_rows,
        "subjects_by_class": subjects_by_class,
        "terms": TERMS,
        "terms_by_class": terms_by_class,
        "current_year": datetime.utcnow().year,
    }


