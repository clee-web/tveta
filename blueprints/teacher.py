def exam_template(exam_id):
    with get_db() as db:
        teacher = _current_teacher(db)
        exam = _exam_for_teacher(db, teacher["id"], exam_id)
        cls = db.execute("SELECT * FROM classes WHERE id = ?", (exam["class_id"],)).fetchone()
        students = students_in_class(db, cls)

    wb = build_exam_workbook(exam, students)
    stream = io.BytesIO()
    wb.save(stream)
    stream.seek(0)

    safe_title = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in exam["title"])
    filename = f"exam_{exam_id}_{safe_title}.xlsx"
    return send_file(
        stream,
        as_attachment=True,
        download_name=filename,
        mimetype="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    )


@bp.route("/exams/<int:exam_id>/upload", methods=["POST"])
@teacher_login_required
def exam_upload(exam_id):
    file_storage = request.files.get("results_file")
    if not file_storage or not file_storage.filename:
        flash("Choose the completed Excel file to upload.", "danger")
        return redirect(url_for("teacher.exam_detail", exam_id=exam_id))

    with get_db() as db:
        teacher = _current_teacher(db)
        exam = _exam_for_teacher(db, teacher["id"], exam_id)
        cls = db.execute("SELECT * FROM classes WHERE id = ?", (exam["class_id"],)).fetchone()
        students = students_in_class(db, cls)
        by_adm = {s["admission_number"]: s for s in students}

        try:
            rows = read_exam_workbook(file_storage.stream)
        except Exception as exc:  # noqa: BLE001 - surface any parse error to the user
            flash(f"Could not read the workbook: {exc}", "danger")
            return redirect(url_for("teacher.exam_detail", exam_id=exam_id))

        now = datetime.utcnow().isoformat()
        updated = 0
        skipped = []
        for admission_number, raw_score in rows:
            student = by_adm.get(admission_number)
            if not student:
                skipped.append(admission_number)
                continue
            if raw_score is None or str(raw_score).strip() == "":
                continue
            try:
                value = float(raw_score)
            except (TypeError, ValueError):
                skipped.append(admission_number)
                continue

            value = max(0.0, min(value, float(exam["max_score"])))
            grade = compute_grade(value, exam["max_score"])
            db.execute(
                """INSERT INTO exam_results (exam_id, student_id, score, grade, updated_at)
                   VALUES (?, ?, ?, ?, ?)
                   ON CONFLICT(exam_id, student_id)
                   DO UPDATE SET score = excluded.score,
                                 grade = excluded.grade,
                                 updated_at = excluded.updated_at""",
                (exam_id, student["id"], value, grade, now),
            )
            updated += 1

    message = f"Results updated for {updated} student(s)."
    if skipped:
        message += f" Skipped {len(skipped)} unrecognised row(s): {', '.join(skipped[:5])}."
    flash(message, "success" if updated else "warning")
    return redirect(url_for("teacher.exam_detail", exam_id=exam_id))


@bp.route("/exams/<int:exam_id>/results", methods=["POST"])
@teacher_login_required
def save_results(exam_id):
    """Grade in the browser. An empty box is left alone, exactly like the workbook
    import, so a partially filled sheet never wipes existing scores."""
    with get_db() as db:
        teacher = _current_teacher(db)
        exam = _exam_for_teacher(db, teacher["id"], exam_id)
        cls = db.execute("SELECT * FROM classes WHERE id = ?", (exam["class_id"],)).fetchone()
        students = {str(s["id"]): s for s in students_in_class(db, cls)}
        max_score = float(exam["max_score"])
        now = datetime.utcnow().isoformat()

        saved = clamped = 0
        rejected = []
        for field, raw in request.form.items():
            if not field.startswith("score-"):
                continue
            student = students.get(field[len("score-"):])
            if not student:
                continue
            raw = (raw or "").strip()
            if not raw:
                continue
            try:
                value = float(raw)
            except ValueError:
                rejected.append(student["full_name"])
                continue

            if value < 0 or value > max_score:
                value = max(0.0, min(value, max_score))
                clamped += 1
            db.execute(
                """INSERT INTO exam_results (exam_id, student_id, score, grade, updated_at)
                   VALUES (?, ?, ?, ?, ?)
                   ON CONFLICT(exam_id, student_id)
                   DO UPDATE SET score = excluded.score,
                                 grade = excluded.grade,
                                 updated_at = excluded.updated_at""",
                (exam_id, student["id"], value, compute_grade(value, max_score), now),
            )
            saved += 1

    if not saved and not rejected:
        flash("Nothing was saved — type at least one score.", "warning")
    else:
        message = f"Saved {saved} score(s)."
        if clamped:
            message += f" {clamped} adjusted to the maximum of {max_score:g}."
        if rejected:
            message += f" Not a number, skipped: {', '.join(rejected[:3])}."
        flash(message, "success" if saved else "warning")
    return redirect(url_for("teacher.exam_detail", exam_id=exam_id))


