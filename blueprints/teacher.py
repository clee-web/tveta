@bp.route("/login", methods=["GET", "POST"])
def login():
    if session.get("teacher_id"):
        return redirect(url_for("teacher.dashboard"))

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        with get_db() as db:
            teacher = db.execute(
                "SELECT * FROM teachers WHERE username = ?", (username,)
            ).fetchone()

        if teacher and check_password_hash(teacher["password_hash"], password):
            session.clear()
            session["teacher_id"] = teacher["id"]
            session["teacher_name"] = teacher["full_name"]
            if teacher["must_change_password"]:
                flash("Welcome! Please set a new password to continue.", "info")
                return redirect(url_for("teacher.set_password"))
            flash(f"Welcome, {teacher['full_name']}.", "success")
            return redirect(url_for("teacher.dashboard"))

        flash("Invalid username or password.", "danger")

    return render_template("teacher_login.html")


@bp.route("/set-password", methods=["GET", "POST"])
def set_password():
    """First-login step: replace the password generated by the admin."""
    if not session.get("teacher_id"):
        flash("Please log in to the teacher portal.", "warning")
        return redirect(url_for("teacher.login"))

    with get_db() as db:
        teacher = db.execute(
            "SELECT * FROM teachers WHERE id = ?", (session["teacher_id"],)
        ).fetchone()

        if not teacher:
            session.clear()
            return redirect(url_for("teacher.login"))

        if not teacher["must_change_password"]:
            return redirect(url_for("teacher.dashboard"))

        if request.method == "POST":
            new = request.form.get("new_password", "")
            confirm = request.form.get("confirm_password", "")

            if len(new) < 8:
                flash("The new password must be at least 8 characters.", "danger")
            elif new != confirm:
                flash("The new passwords do not match.", "danger")
            else:
                db.execute(
                    """UPDATE teachers
                       SET password_hash = ?, initial_password = NULL, must_change_password = 0
                       WHERE id = ?""",
                    (generate_password_hash(new), teacher["id"]),
                )
                # Same reasoning as the student portal: the session is already
                # proven, so keep the teacher signed in with the new password
                # instead of making them log straight back in.
                flash("Password changed. You are signed in with your new password.", "success")
                return redirect(url_for("teacher.dashboard"))

    return render_template("teacher_set_password.html", teacher=teacher)


